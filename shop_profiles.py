"""Portable shop requirements and honest capability checks for SVG exports."""
import math


def validate_profile(profile):
    if not isinstance(profile, dict):
        raise ValueError('Choose a shop profile.')
    result = {}
    for key, maximum in [('name',80),('rip',80),('iccProfile',160),('cutSpot',80),('cutLayer',80),('finishingSoftware',80)]:
        value = profile.get(key)
        if not isinstance(value,str) or len(value)>maximum or any(ord(c)<32 or ord(c)==127 for c in value) or (key in ('name','rip') and not value.strip()):
            raise ValueError('Check '+key+' in the shop profile.')
        result[key] = value.strip()
    for key, values in [('format',('pdf','eps','svg')),('colorMode',('preserve','cmyk','rgb')),('registrationOwner',('rip','finishing','file','none')),('mediaOwner',('rip','external')),('jobLogOwner',('rip','external'))]:
        if profile.get(key) not in values:
            raise ValueError('Invalid shop profile '+key+'.')
        result[key] = profile[key]
    formats = profile.get('acceptedFormats')
    if not isinstance(formats,list) or not 1<=len(formats)<=5 or any(f not in ('pdf','eps','ai','svg','tiff') for f in formats):
        raise ValueError('Invalid accepted file formats.')
    result['acceptedFormats'] = list(dict.fromkeys(formats))
    bleed = profile.get('bleedMm')
    if 'bleedMm' not in profile or (bleed is not None and (type(bleed) not in (int,float) or not math.isfinite(bleed) or not 0<=bleed<=100)):
        raise ValueError('Bleed must be blank or between 0 and 100 mm.')
    result['bleedMm'] = bleed
    if result['cutLayer'] and not result['cutSpot']:
        raise ValueError('Name the cut spot color, or clear the cut layer.')
    return result


def inspect_output(profile):
    p = validate_profile(profile)
    issues = []
    if p['format']!='svg':
        issues.append(p['format'].upper()+' export is not available in this build.')
    if p['colorMode']!='preserve':
        issues.append(p['colorMode'].upper()+' conversion and verification are not available.')
    if p['iccProfile']:
        issues.append('ICC profile '+p['iccProfile']+' has not been applied or verified.')
    if p['bleedMm'] is None:
        issues.append('Confirm the required bleed.')
    elif p['bleedMm']>0:
        issues.append('Artwork bleed has not been generated or verified.')
    if p['cutSpot']:
        issues.append('A named '+p['cutSpot']+' spot separation'+(' on layer '+p['cutLayer'] if p['cutLayer'] else '')+' has not been generated or verified.')
    if p['registrationOwner']=='file':
        issues.append('Registration marks are not generated by this build.')
    return {'ready':not issues,'actualFormat':'svg','issues':issues}
